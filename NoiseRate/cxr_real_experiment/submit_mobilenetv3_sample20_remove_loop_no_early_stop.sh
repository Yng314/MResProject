#!/bin/bash
set -euo pipefail

PROJECT_DIR="/vol/gpudata/yz3522-llmtest/MResProject"
SCRIPT_DIR="${PROJECT_DIR}/NoiseRate/cxr_real_experiment"
STAMP="$(date +%Y%m%d_%H%M%S)"
OUTPUT_ROOT="${OUTPUT_ROOT_OVERRIDE:-/vol/bitbucket/yz3522/NoiseRate_results_archive/cxr_real_experiment/results_mobilenetv3_sample20_remove_loop_no_early_stop/${STAMP}}"
LOOP_COUNT="${LOOP_COUNT_OVERRIDE:-5}"
TOP_FRACTION="${TOP_FRACTION_OVERRIDE:-0.20}"
SEED="${SEED_OVERRIDE:-13}"

mkdir -p "${OUTPUT_ROOT}" "${PROJECT_DIR}/slurm_logs"

JOB_REMOVE="$(
  MODEL_BACKBONE_OVERRIDE=mobilenet_v3_small_scratch \
  MODEL_TAG_OVERRIDE=mobilenet_v3_small_scratch_noes \
  OOF_BATCH_SIZE_OVERRIDE="${OOF_BATCH_SIZE_OVERRIDE:-32}" \
  TRAIN_BATCH_SIZE_OVERRIDE="${TRAIN_BATCH_SIZE_OVERRIDE:-32}" \
  TRAIN_EPOCHS_OVERRIDE="${TRAIN_EPOCHS_OVERRIDE:-50}" \
  TRAIN_EARLY_STOPPING_PATIENCE_OVERRIDE="${TRAIN_EARLY_STOPPING_PATIENCE_OVERRIDE:-100000}" \
  TRAIN_RECOVER_BEST_WEIGHTS_OVERRIDE=0 \
  sbatch --parsable --job-name=mbv3-s20-rm-noes \
    "${SCRIPT_DIR}/run_xrv_iterative_sample20_branch.sh" \
    "remove_only" "${OUTPUT_ROOT}" "${LOOP_COUNT}" "${TOP_FRACTION}" "${SEED}"
)"

cat > "${OUTPUT_ROOT}/submission_summary.txt" <<TXT
OUTPUT_ROOT=${OUTPUT_ROOT}
LOOP_COUNT=${LOOP_COUNT}
TOP_FRACTION=${TOP_FRACTION}
SEED=${SEED}
MODEL_BACKBONE=mobilenet_v3_small_scratch
TRAIN_EPOCHS=${TRAIN_EPOCHS_OVERRIDE:-50}
TRAIN_EARLY_STOPPING_PATIENCE=${TRAIN_EARLY_STOPPING_PATIENCE_OVERRIDE:-100000}
TRAIN_RECOVER_BEST_WEIGHTS=0
REMOVE_ONLY_JOB=${JOB_REMOVE}
TXT

echo "OUTPUT_ROOT=${OUTPUT_ROOT}"
echo "LOOP_COUNT=${LOOP_COUNT}"
echo "TOP_FRACTION=${TOP_FRACTION}"
echo "SEED=${SEED}"
echo "MODEL_BACKBONE=mobilenet_v3_small_scratch"
echo "TRAIN_EPOCHS=${TRAIN_EPOCHS_OVERRIDE:-50}"
echo "TRAIN_EARLY_STOPPING_PATIENCE=${TRAIN_EARLY_STOPPING_PATIENCE_OVERRIDE:-100000}"
echo "TRAIN_RECOVER_BEST_WEIGHTS=0"
echo "REMOVE_ONLY_JOB=${JOB_REMOVE}"
